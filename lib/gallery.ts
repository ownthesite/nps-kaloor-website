export function generateImages(
  slug: string,
  count: number
) {
  const normalized = slug.replace(/_/g, '-')

  return Array.from({ length: count }, (_, i) => {
    const num = String(i + 1).padStart(2, '0')

    return `/events-gallery/${slug}/${normalized}-${num}.webp`
  })
}